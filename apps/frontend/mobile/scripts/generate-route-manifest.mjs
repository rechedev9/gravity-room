import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIRECTORY = dirname(fileURLToPath(import.meta.url));
const MOBILE_DIRECTORY = resolve(SCRIPT_DIRECTORY, '..');

function readArgument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function normalizePath(value) {
  return value.split(sep).join('/');
}

function collectRouteFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolutePath = resolve(directory, entry.name);
    if (entry.isDirectory()) {
      return collectRouteFiles(absolutePath);
    }

    return /\.(?:ts|tsx|js|jsx)$/.test(entry.name) ? [absolutePath] : [];
  });
}

function toRouteFileId(appDirectory, absolutePath) {
  return normalizePath(relative(appDirectory, absolutePath)).replace(/\.(?:ts|tsx|js|jsx)$/, '');
}

function toPublicPath(routeFileId) {
  const segments = routeFileId
    .split('/')
    .filter((segment) => segment !== '_layout' && !/^\(.+\)$/.test(segment));

  if (segments.at(-1) === 'index') {
    segments.pop();
  }

  return segments.length === 0 ? '/' : `/${segments.join('/')}`;
}

function createRouteManifestSource(appDirectory) {
  const routeFileIds = collectRouteFiles(appDirectory)
    .map((filePath) => toRouteFileId(appDirectory, filePath))
    .sort();
  const publicPaths = [...new Set(routeFileIds.map(toPublicPath))].sort();
  const serialize = (values) => values.map((value) => `  '${value}',`).join('\n');

  return `// Generated by scripts/generate-route-manifest.mjs. Do not edit by hand.
export const ROUTE_FILE_IDS = [
${serialize(routeFileIds)}
] as const;

export const PUBLIC_ROUTE_PATHS = [
${serialize(publicPaths)}
] as const;

export type RouteFileId = (typeof ROUTE_FILE_IDS)[number];
export type PublicRoutePath = (typeof PUBLIC_ROUTE_PATHS)[number];
`;
}

const appDirectory = resolve(readArgument('--app-dir') ?? resolve(MOBILE_DIRECTORY, 'src/app'));
const outputPath = resolve(
  readArgument('--output') ??
    resolve(MOBILE_DIRECTORY, 'src/navigation/route-manifest.generated.ts')
);
const source = createRouteManifestSource(appDirectory);

if (process.argv.includes('--check')) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== source) {
    console.error(
      'Expo Router manifest is missing or stale. Run: pnpm --filter mobile routes:generate'
    );
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, source);
}
